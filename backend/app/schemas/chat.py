"""
Pydantic Schemas for Chat and Code Q&A Endpoints.
"""

from typing import List, Optional
from pydantic import BaseModel, Field


class ChatRequest(BaseModel):
    """
    Request model for POST /chat.
    """
    repository_id: str = Field(..., description="Target indexed repository identifier", examples=["octocat__hello-world"])
    question: str = Field(..., description="Natural language question about the codebase", examples=["How does authentication work in this project?"])
    branch: Optional[str] = Field(default=None, description="Optional branch filter for the query")
    top_k: Optional[int] = Field(default=5, ge=1, le=20, description="Maximum number of relevant code chunks to retrieve")


class SourceCitationSchema(BaseModel):
    """
    Evidence citation representing an exact file and line range.
    """
    path: str = Field(..., description="Relative file path in the repository", examples=["src/auth/jwt_service.py"])
    start_line: int = Field(..., description="Starting line number (1-indexed)", examples=[15])
    end_line: int = Field(..., description="Ending line number (1-indexed)", examples=[42])
    chunk_id: str = Field(..., description="Unique chunk identifier", examples=["chunk_a1b2c3d4"])
    score: float = Field(..., description="Cosine similarity relevance score", examples=[0.8842])


class ChatResponse(BaseModel):
    """
    Response model for POST /chat.
    """
    question: str = Field(..., description="Original user question")
    repository_id: str = Field(..., description="Target repository queried")
    answer: str = Field(..., description="Evidence-grounded explanation generated by Gemini")
    sources: List[SourceCitationSchema] = Field(default_factory=list, description="List of source file references supporting the answer")
    files_analyzed: List[str] = Field(default_factory=list, description="List of repository files analyzed for this question")
    insufficient_context: bool = Field(..., description="True if retrieved code did not contain enough evidence")
    retrieved_chunks_count: int = Field(..., description="Number of chunks retrieved from vector store")
    latency_ms: float = Field(..., description="Round-trip latency in milliseconds")
